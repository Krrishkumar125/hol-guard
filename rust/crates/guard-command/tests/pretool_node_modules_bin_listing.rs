#![cfg(unix)]

//! `ls node_modules/.bin/<tool>` is how work checks whether a test runner or a
//! bundler is installed. `.bin` is a hidden component, so the hidden-path
//! screen refused a listing of any directory below it while it allowed the
//! `.bin` directory itself and the files in it. A `.bin` directly below
//! `node_modules` is generated tooling named by the package manager, so a read
//! of it continues; a `.bin` anywhere else, and a second hidden component
//! below this one, keep their review.

use crate::git_helper_fixture as fixture;
use fixture::{evaluate_pre_tool_envelope_with_context, FixtureCleanup};
use serde_json::json;

struct Layout {
    home: std::path::PathBuf,
    project: std::path::PathBuf,
    _cleanup: FixtureCleanup,
}

fn layout(name: &str) -> Layout {
    let root = std::env::temp_dir().join(format!("guard-{name}-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&root);
    std::fs::create_dir_all(&root).unwrap();
    let root = fixture::canonical_spelling(&root);
    let cleanup = FixtureCleanup(root.clone());
    let home = root.join("home");
    let project = home.join("work/app");
    for relative in [
        "node_modules/.bin/vitest",
        "node_modules/.bin/esbuild/lib",
        "node_modules/.bin/.ssh",
        "node_modules/lodash",
        "tools/.bin/runner",
    ] {
        std::fs::create_dir_all(project.join(relative)).unwrap();
    }
    std::fs::write(project.join("package.json"), "{}\n").unwrap();
    std::fs::write(project.join("node_modules/.bin/tsc"), "#!/bin/sh\n").unwrap();
    Layout {
        home,
        project,
        _cleanup: cleanup,
    }
}

fn decide(layout: &Layout, command: &str) -> String {
    evaluate_pre_tool_envelope_with_context(
        "omp",
        "PreToolUse",
        &json!({"tool_name": "bash", "tool_input": {"command": command}}),
        None,
        None,
        layout.home.to_str(),
        layout.project.to_str(),
    )
    .decision
}

#[test]
fn an_installed_runner_below_node_modules_bin_lists_without_review() {
    let layout = layout("node-bin-listing");
    for relative in [
        "node_modules/.bin",
        "node_modules/.bin/vitest",
        "node_modules/.bin/esbuild/lib",
        "node_modules/.bin/tsc",
    ] {
        let target = fixture::shell_word(&layout.project.join(relative));
        for command in [
            format!("ls {target}"),
            format!("ls {target} 2>&1 | head -1"),
        ] {
            assert_eq!(decide(&layout, &command), "allow", "{command}");
        }
    }
}

#[test]
fn a_bin_elsewhere_and_a_credential_folder_below_one_keep_their_review() {
    let layout = layout("node-bin-review");
    for relative in ["tools/.bin/runner", "node_modules/.bin/.ssh"] {
        let target = fixture::shell_word(&layout.project.join(relative));
        let command = format!("ls {target}");
        assert_ne!(decide(&layout, &command), "allow", "{command}");
    }
}
